        ];
    }

    /**
     * Ensure URL has scheme (http/https) if external
     */
    public function getFormattedUrlAttribute(): string
    {
        $url = trim($this->url);
        if (empty($url)) {
            return '#';
        }
        if (str_starts_with($url, 'http://') || str_starts_with($url, 'https://') || str_starts_with($url, '/')) {
            return $url;
        }
        return 'https://' . $url;
    }

